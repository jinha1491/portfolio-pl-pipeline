-- Run once in a Snowflake worksheet as ACCOUNTADMIN.
-- Paste your public key (the base64 text between the BEGIN/END lines) into RSA_PUBLIC_KEY.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS PORTFOLIO_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS PORTFOLIO;

CREATE ROLE IF NOT EXISTS PORTFOLIO_ROLE;
GRANT USAGE ON WAREHOUSE PORTFOLIO_WH TO ROLE PORTFOLIO_ROLE;
GRANT ALL ON DATABASE PORTFOLIO TO ROLE PORTFOLIO_ROLE;
GRANT ROLE PORTFOLIO_ROLE TO ROLE SYSADMIN;

CREATE USER IF NOT EXISTS PORTFOLIO_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = PORTFOLIO_ROLE
  DEFAULT_WAREHOUSE = PORTFOLIO_WH
  RSA_PUBLIC_KEY = 'PASTE_PUBLIC_KEY_HERE';
GRANT ROLE PORTFOLIO_ROLE TO USER PORTFOLIO_SVC;
