import os

import pandas as pd
import psycopg

DATABASE_URL = os.environ.get(
    "DATABASE_URL",
    "postgresql://postgres:postgres@localhost:5432/portfolio",
)

SCHEMA = """
CREATE TABLE IF NOT EXISTS holdings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stock_name TEXT NOT NULL,
    symbol TEXT NOT NULL UNIQUE,
    total_quantity DOUBLE PRECISION NOT NULL,
    account_quantities JSONB NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person TEXT NOT NULL,
    symbol TEXT,
    stock_name TEXT,
    side TEXT NOT NULL CHECK (side IN ('BUY', 'SELL')),
    trade_date DATE NOT NULL,
    quantity DOUBLE PRECISION NOT NULL CHECK (quantity > 0),
    price DOUBLE PRECISION NOT NULL CHECK (price >= 0),
    fees DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (fees >= 0),
    created_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS lots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    buy_txn_id BIGINT NOT NULL REFERENCES transactions(id),
    person TEXT NOT NULL,
    symbol TEXT NOT NULL,
    buy_date DATE NOT NULL,
    buy_price DOUBLE PRECISION NOT NULL,
    remaining_qty DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS matches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sell_txn_id BIGINT NOT NULL REFERENCES transactions(id),
    buy_lot_id BIGINT NOT NULL REFERENCES lots(id),
    person TEXT NOT NULL,
    symbol TEXT NOT NULL,
    buy_date DATE NOT NULL,
    sell_date DATE NOT NULL,
    matched_qty DOUBLE PRECISION NOT NULL,
    buy_price DOUBLE PRECISION NOT NULL,
    sell_price DOUBLE PRECISION NOT NULL,
    realized_pl DOUBLE PRECISION NOT NULL,
    term TEXT NOT NULL CHECK (term IN ('SHORT', 'LONG'))
);

CREATE TABLE IF NOT EXISTS daily_prices (
    symbol TEXT NOT NULL,
    price_date DATE NOT NULL,
    close DOUBLE PRECISION NOT NULL CHECK (close > 0),
    loaded_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (symbol, price_date)
);

CREATE TABLE IF NOT EXISTS portfolio_snapshots (
    snapshot_date DATE NOT NULL,
    person TEXT NOT NULL,
    symbol TEXT NOT NULL,
    quantity DOUBLE PRECISION NOT NULL,
    close DOUBLE PRECISION NOT NULL,
    market_value DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (snapshot_date, person, symbol)
);

CREATE TABLE IF NOT EXISTS ingested_files (
    file_hash TEXT PRIMARY KEY,
    file_name TEXT NOT NULL,
    kind TEXT NOT NULL CHECK (kind IN ('holdings', 'transactions')),
    rows_loaded INTEGER NOT NULL,
    ingested_at TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_txn_main ON transactions(person, symbol, trade_date);
CREATE INDEX IF NOT EXISTS idx_lots_main ON lots(person, symbol, buy_date);
CREATE INDEX IF NOT EXISTS idx_matches_main ON matches(person, symbol, sell_date);
"""


def connect():
    # libpq tries Kerberos (GSSAPI) first by default, and on macOS that crashes inside
    # forked processes, which is how Airflow's LocalExecutor runs tasks.
    return psycopg.connect(DATABASE_URL, gssencmode="disable")


def init_db():
    with connect() as c:
        c.execute(SCHEMA)


def execute(query, params=None):
    """Run one write query in its own transaction and return the number of rows affected."""
    with connect() as c:
        return c.execute(query, params).rowcount


def fetch_df(query, params=None):
    """Run a read query and return a DataFrame."""
    with connect() as c:
        cur = c.execute(query, params)
        return pd.DataFrame(cur.fetchall(), columns=[d.name for d in cur.description])
